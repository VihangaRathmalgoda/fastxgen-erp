<#
.SYNOPSIS
    Builds the SQL project offline and copies the generated SQL files to artifacts/sql.

.DESCRIPTION
    Does NOT connect to any SQL Server. Output:
      artifacts/sql/FastXGenErp_Create_<timestamp>.sql   creates a NEW database from scratch
                                                          (drops an existing database of the same name;
                                                          run only on an empty, approved environment)
      artifacts/sql/FastXGen.Erp.Database.dacpac         model used to generate upgrade scripts
    Upgrade scripts for an existing database are generated by the person authorised for that
    environment (ADR 0003).
#>
[CmdletBinding()]
param(
    [ValidateSet('Debug', 'Release')]
    [string] $Configuration = 'Release'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$project = Join-Path $root 'database/FastXGen.Erp.Database/FastXGen.Erp.Database.sqlproj'
$binDir = Join-Path $root "database/FastXGen.Erp.Database/bin/$Configuration"
$outDir = Join-Path $root 'artifacts/sql'

dotnet build $project -c $Configuration
if ($LASTEXITCODE -ne 0) { throw 'SQL project build failed.' }

New-Item -ItemType Directory -Force -Path $outDir | Out-Null
$stamp = Get-Date -Format 'yyyyMMdd-HHmm'

Copy-Item (Join-Path $binDir 'FastXGen.Erp.Database_Create.sql') (Join-Path $outDir "FastXGenErp_Create_$stamp.sql")
Copy-Item (Join-Path $binDir 'FastXGen.Erp.Database.dacpac') (Join-Path $outDir 'FastXGen.Erp.Database.dacpac') -Force

Write-Host "SQL scripts written to $outDir"
